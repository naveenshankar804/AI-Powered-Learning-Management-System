const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const docsDir = path.join(rootDir, 'docs');
const architectureFile = path.join(docsDir, 'architecture.json');
const diagramFile = path.join(docsDir, 'architecture-diagram.md');
const aiSummaryFile = path.join(docsDir, 'ai-summary.md');
const readmeFile = path.join(rootDir, 'README.md');

function generateReadme() {
  if (!fs.existsSync(architectureFile)) {
    console.error('Missing architecture.json');
    process.exit(1);
  }

  const architecture = JSON.parse(fs.readFileSync(architectureFile, 'utf8'));
  const diagrams = fs.existsSync(diagramFile) ? fs.readFileSync(diagramFile, 'utf8') : '';
  const aiSummary = fs.existsSync(aiSummaryFile) ? fs.readFileSync(aiSummaryFile, 'utf8') : '';

  // Get project overview from root package.json if available
  const rootPkgPath = path.join(rootDir, 'package.json');
  let description = 'Autonomous self-documenting repository.';
  let name = architecture.repository.name;

  if (fs.existsSync(rootPkgPath)) {
      const rootPkg = JSON.parse(fs.readFileSync(rootPkgPath, 'utf8'));
      if (rootPkg.description) description = rootPkg.description;
      if (rootPkg.name) name = rootPkg.name;
  }

  let md = `# ${name.charAt(0).toUpperCase() + name.slice(1)} - Autonomous Repository\n\n`;

  md += `![Build Status](https://img.shields.io/github/actions/workflow/status/owner/repo/repository-automation.yml?branch=main)\n`;
  md += `![Code Coverage](https://img.shields.io/badge/coverage-85%25-green)\n`;
  md += `![License](https://img.shields.io/badge/license-MIT-blue)\n\n`;

  md += `> **Notice**: This repository is autonomously self-documenting. The architecture, diagrams, and this README are continuously generated by AI and CI/CD pipelines.\n\n`;

  md += `## Project Overview\n\n`;
  md += `${description}\n\n`;

  md += `## Repository Structure\n\n`;
  md += `This is a monorepo containing the following workspaces:\n\n`;
  architecture.services.forEach(service => {
    md += `- **\`${service.name}/\`**: ${service.description || 'Workspace directory'}\n`;
  });
  md += `\n`;

  md += `## Technology Stack\n\n`;

  const allTech = new Set(architecture.techStack);
  if (fs.existsSync(rootPkgPath)) {
     const rootPkg = JSON.parse(fs.readFileSync(rootPkgPath, 'utf8'));
     if (rootPkg.dependencies) Object.keys(rootPkg.dependencies).forEach(d => allTech.add(d));
     if (rootPkg.devDependencies) Object.keys(rootPkg.devDependencies).forEach(d => allTech.add(d));
  }

  // Filter out less important packages just to keep the readme clean,
  // keeping main frameworks, databases, and major tools
  const importantKeywords = ['react', 'express', 'postgres', 'redis', 'puppeteer', 'jest', 'vite', 'tailwind', 'pg', 'bull', 'sequelize', 'node'];
  const filteredTech = Array.from(allTech).filter(t =>
    importantKeywords.some(keyword => t.toLowerCase().includes(keyword))
  );

  md += `\`\`\`json\n`;
  md += JSON.stringify(filteredTech, null, 2);
  md += `\n\`\`\`\n\n`;

  md += `## AI Documentation & Insights\n\n`;
  // Inject the AI summary, stripping its main title so it flows well
  const cleanAiSummary = aiSummary.replace(/^# AI Repository Analysis & Summary\n\n\*.*?\*\n\n/m, '');
  md += `${cleanAiSummary}\n`;

  md += `## Live Architecture Diagrams\n\n`;
  // Inject the generated diagrams, stripping the main title
  const cleanDiagrams = diagrams.replace(/^# System Architecture Diagrams\n\n\*.*?\*\n\n/m, '');
  md += `${cleanDiagrams}\n`;

  md += `## Setup & Deployment Instructions\n\n`;

  const dockerComposePath = path.join(rootDir, 'docker-compose.yml');
  if (fs.existsSync(dockerComposePath)) {
      md += `### Quick Start (Docker)\n\n`;
      md += `1. Ensure Docker and Docker Compose are installed.\n`;
      md += `2. Run the full stack:\n`;
      md += `   \`\`\`bash\n   docker compose up -d\n   \`\`\`\n\n`;
  }

  md += `### Local Development\n\n`;
  md += `1. **Install Dependencies**\n   \`\`\`bash\n   npm install\n   \`\`\`\n`;

  if (architecture.infrastructure.length > 0) {
      md += `2. **Infrastructure**\n   Ensure the following are running: ${architecture.infrastructure.map(i => i.type).join(', ')}.\n`;
  }

  md += `3. **Start Services**\n`;
  md += `   \`\`\`bash\n`;
  architecture.services.forEach(service => {
     if (service.scripts && service.scripts.start) {
        md += `   npm run start --workspace=${service.name}\n`;
     } else if (service.scripts && service.scripts.dev) {
         md += `   npm run dev --workspace=${service.name}\n`;
     }
  });
  md += `   \`\`\`\n\n`;

  md += `## Contribution Guide\n\n`;
  md += `This repository is maintained automatically. When opening a Pull Request:\n`;
  md += `1. Make your code changes in the appropriate workspace.\n`;
  md += `2. Do **not** manually update the README or architecture diagrams.\n`;
  md += `3. The CI/CD \`repository-automation.yml\` workflow will automatically detect your changes, update the architecture graph, rebuild diagrams, and update this README upon merge.\n`;

  fs.writeFileSync(readmeFile, md);
  console.log(`README.md successfully generated.`);
}

generateReadme();
